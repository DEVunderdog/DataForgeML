"""Build the command index inside the package Skill, ``skill/SKILL.md`` (ADR-0108, ADR-0112).

The Skill is hand-written prose around one generated block: one usage line per
command, grouped by phase, between :data:`BEGIN_MARKER` and :data:`END_MARKER`.
A usage line holds the command, its required flags and its summary line, and
marks a command whose cost grows with the data. It never holds the optional
flags; ``dataforge <command> --help`` lists those. A contract test fails when
the block is stale. Rebuild it after changing an Operation with::

    uv run python -m dataforge_ml._boundary._skill_build
"""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

from .._cli import kebab, takes_json
from ._help_build import PHASE_ORDER
from ._operation import OperationSpec, operations

#: The package Skill, shipped inside the package.
SKILL_FILE = Path(__file__).parents[1] / "skill" / "SKILL.md"
#: Most ``o200k_base`` tokens the whole Skill file may have (ADR-0108).
SKILL_BUDGET_TOKENS = 2_000
#: The lines the generated command index sits between.
BEGIN_MARKER = (
    "<!-- BEGIN COMMANDS: generated by "
    "`uv run python -m dataforge_ml._boundary._skill_build` -->"
)
END_MARKER = "<!-- END COMMANDS -->"
#: The mark on a command whose cost grows with the data.
BACKGROUND_MARK = "(background)"


def _usage_line(spec: OperationSpec) -> str:
    parts = [f"dataforge {kebab(spec.name)}"]
    for name, field in spec.args_model.model_fields.items():
        if field.is_required():
            value = "json" if takes_json(spec, name) else name
            parts.append(f"--{kebab(name)} <{value}>")
    mark = f" {BACKGROUND_MARK}" if spec.scales_with_data else ""
    return f"- `{' '.join(parts)}`{mark}: {spec.docstring.summary}"


def command_index(specs: Mapping[str, OperationSpec] | None = None) -> str:
    """Return the generated command index, markers included.

    Parameters
    ----------
    specs : mapping of str to OperationSpec, optional
        The Operations, by name. Every registered Operation by default.

    Returns
    -------
    str
        The begin marker, one ``### <phase>`` heading per phase in workflow
        order with one usage line per command under it, then the end marker.
    """
    specs = dict(operations() if specs is None else specs)
    lines = [BEGIN_MARKER]
    for phase in PHASE_ORDER:
        names = sorted(name for name, spec in specs.items() if spec.phase == phase)
        if names:
            lines += ["", f"### {phase}", *(_usage_line(specs[name]) for name in names)]
    return "\n".join([*lines, "", END_MARKER])


def skill_text(current: str, specs: Mapping[str, OperationSpec] | None = None) -> str:
    """Return the Skill text with its command index regenerated.

    Parameters
    ----------
    current : str
        The Skill's text as it is.
    specs : mapping of str to OperationSpec, optional
        The Operations, by name. Every registered Operation by default.

    Returns
    -------
    str
        ``current`` with everything from the begin marker to the end marker
        replaced by :func:`command_index`.

    Raises
    ------
    ValueError
        When ``current`` lacks either marker, or has them out of order.
    """
    start = current.find(BEGIN_MARKER)
    end = current.find(END_MARKER)
    if start < 0 or end < start:
        raise ValueError("SKILL.md needs the command index markers, begin before end")
    return current[:start] + command_index(specs) + current[end + len(END_MARKER):]


def write_skill(path: Path = SKILL_FILE) -> None:
    """Regenerate the command index of the Skill at ``path``, in place.

    Parameters
    ----------
    path : Path, optional
        The Skill file; the packaged ``skill/SKILL.md`` by default.
    """
    path.write_text(skill_text(path.read_text("utf-8")), "utf-8")


if __name__ == "__main__":
    write_skill()
